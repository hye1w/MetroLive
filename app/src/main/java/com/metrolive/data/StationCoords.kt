    /** 최근접 역 (이름, 대략 거리 m) */
    fun nearest(lat: Double, lng: Double): Pair<String, Int>? =
        coords.minByOrNull { (_, c) -> dist2(lat, lng, c.first, c.second) }
            ?.let { (name, c) ->
                name to (sqrt(dist2(lat, lng, c.first, c.second)) * 111_000).toInt()
            }

    private fun dist2(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val dLat = lat1 - lat2
        val dLng = (lng1 - lng2) * cos(Math.toRadians(lat1))
        return dLat * dLat + dLng * dLng
    }
